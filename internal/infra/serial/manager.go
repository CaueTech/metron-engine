package serial

import (
	"errors"
	"fmt"
	"time"

	"github.com/CaueTech/metron-engine/internal/domain"
	"github.com/CaueTech/metron-engine/internal/infra/proto"
	"github.com/google/uuid"

	// Esse alias evita conflito com o pacote interno
	protobuf "google.golang.org/protobuf/proto"
)

/*
	Note that the Event struct here is the Protobuf one, not from the domain. One is built upon the other.
*/

var (
	ErrNullEvent        = errors.New("event cannot be nil")
	ErrNullPayload      = errors.New("payload cannot be nil")
	ErrUnmarshal        = errors.New("couldn't convert bytes to event object")
)

func Serialize(event *domain.Event) ([]byte, error) {
	if event == nil {
		return nil, ErrNullEvent
	}

	protoEvent := &proto.Event{
		Id:              event.ID().String(),
		SourceId:        event.SourceID().String(),
		EventType:       proto.EventType(event.Type()),
		TimestampUnixMs: event.Timestamp().UnixMilli(),
	}

	// Some conversions were necessary to follow the standard generated by Protobuf in event.pb.go.

	// This function already returns a []byte, err.
	return protobuf.Marshal(protoEvent)
}

func Deserialize(payload []byte) (*domain.Event, error) {
	if payload == nil {
		return nil, ErrNullPayload
	}

	var protoMsg proto.Event

	if err := protobuf.Unmarshal(payload, &protoMsg); err != nil {
		return nil, fmt.Errorf("%w: %v", ErrUnmarshal, err)
	}

	eventID, _ := uuid.Parse(protoMsg.GetId())

	sourceID, _ := uuid.Parse(protoMsg.GetSourceId())

	eventType := domain.EventType(protoMsg.GetEventType())

	timestamp := time.UnixMilli(protoMsg.GetTimestampUnixMs()).UTC()

	return domain.NewEvent(eventID, sourceID, eventType, timestamp), nil
}

