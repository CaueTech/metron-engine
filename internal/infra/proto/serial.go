package proto

import (
	"errors"
	"fmt"
	"time"

	"github.com/CaueTech/metron-engine/internal/domain"
	"github.com/google/uuid"
	"google.golang.org/protobuf/proto"
)

/*
	Note that the Event struct here is the Protobuf one, not from the domain. One is built upon the other.
*/

var (
	ErrNullEvent        = errors.New("event cannot be nil")
	ErrNullPayload      = errors.New("payload cannot be nil")
	ErrUnmarshal        = errors.New("couldn't convert bytes to event object")
	ErrInvalidEventID   = errors.New("event id is missing, not a valid uuid, or nil")
	ErrInvalidSourceID  = errors.New("source id is missing, not a valid uuid, or nil")
	ErrInvalidEventType = errors.New("event type is unknown or out of valid bounds")
	ErrInvalidTimestamp = errors.New("timestamp is zero or outside acceptable limits")
)

func Serialize(event *domain.Event) ([]byte, error) {
	if event == nil {
		return nil, ErrNullEvent
	}

	protoEvent := &Event{
		Id:              event.ID().String(),
		SourceId:        event.SourceID().String(),
		EventType:       EventType(event.Type()),
		TimestampUnixMs: event.Timestamp().UnixMilli(),
	}

	// Some conversions were necessary to follow the standard generated by Protobuf in event.pb.go.

	// This function already returns a []byte, err.
	return proto.Marshal(protoEvent)
}

func Deserialize(payload []byte) (*domain.Event, error) {
	if payload == nil {
		return nil, ErrNullPayload
	}

	var protoMsg Event

	if err := proto.Unmarshal(payload, &protoMsg); err != nil {
		return nil, fmt.Errorf("%w: %v", ErrUnmarshal, err)
	}

	// 2. Validação de regras de negócio (parsing semântico)
	eventID, err := uuid.Parse(protoMsg.GetId())

	if err != nil || eventID == uuid.Nil {
		return nil, ErrInvalidEventID
	}

	sourceID, err := uuid.Parse(protoMsg.GetSourceId())

	if err != nil || sourceID == uuid.Nil {
		return nil, ErrInvalidSourceID
	}

	eventType := domain.EventType(protoMsg.GetEventType())

	if !eventType.IsValid() {
		return nil, ErrInvalidEventType
	}

	// 3. Monta a entidade pura de domínio
	timestamp := time.UnixMilli(protoMsg.GetTimestampUnixMs()).UTC()
	return domain.NewEvent(eventID, sourceID, eventType, timestamp), nil
}
